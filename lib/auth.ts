import "server-only";
import { betterAuth } from "better-auth";
import { drizzleAdapter } from "better-auth/adapters/drizzle";
import { nextCookies } from "better-auth/next-js";
import { emailOTP } from "better-auth/plugins";
import { db } from "@/db";
import * as schema from "@/db/schema";
import { sendVerificationCode } from "@/lib/email";
import {
  PASSWORD_MAX_LENGTH,
  PASSWORD_MIN_LENGTH,
  VERIFICATION_CODE_LENGTH,
  VERIFICATION_CODE_MINUTES,
} from "@/lib/validation/auth";

// Better Auth server config. Reads BETTER_AUTH_SECRET and BETTER_AUTH_URL from the environment.
export const auth = betterAuth({
  appName: "Qrious",
  database: drizzleAdapter(db, { provider: "pg", schema }),
  emailAndPassword: {
    enabled: true,
    minPasswordLength: PASSWORD_MIN_LENGTH,
    maxPasswordLength: PASSWORD_MAX_LENGTH,
    // Sign-up does not sign in: the e-mail must be verified first (6-digit code).
    autoSignIn: false,
    requireEmailVerification: true,
  },
  // No session cookie cache: it would keep a deleted account or a revoked session
  // "signed in" until the cache expires. Every check reads the database.
  emailVerification: {
    sendOnSignUp: true,
    // An unverified student who signs in gets a new code instead of a session.
    sendOnSignIn: true,
    // The right code proves the e-mail: sign the student in right away.
    autoSignInAfterVerification: true,
  },
  socialProviders: {
    google: {
      clientId: process.env.GOOGLE_CLIENT_ID!,
      clientSecret: process.env.GOOGLE_CLIENT_SECRET!,
      // Always show Google's account picker (shared phones and family computers).
      prompt: "select_account",
      // Keep only the e-mail: Qrious shows a pseudo, never a student's real name or photo.
      mapProfileToUser: () => ({ name: "", image: undefined }),
    },
  },
  account: {
    accountLinking: {
      // One way in per e-mail: Google is never joined to an existing password account
      // automatically (decided 2026-10-12). Those students sign in with their password,
      // or reset it; joining Google will be an explicit choice in Paramètres.
      disableImplicitLinking: true,
    },
  },
  user: {
    additionalFields: {
      termsAcceptedAt: { type: "date", required: false },
      ageConfirmedAt: { type: "date", required: false },
    },
  },
  advanced: {
    // uuid ids, generated by Postgres (docs/06-data-model.md).
    database: { generateId: "uuid" },
  },
  // Every auth flow goes through our server actions (server/actions/auth.ts), which
  // check inputs with Zod. These public endpoints would skip those checks (e.g. sign
  // up without the consent boxes), so they are switched off. Server calls
  // (auth.api.*) still work; only outside HTTP requests are refused.
  disabledPaths: [
    "/sign-up/email",
    "/sign-in/email",
    "/sign-in/social",
    "/update-user",
    "/change-email",
    "/send-verification-email",
    "/verify-email",
    "/sign-in/email-otp",
    "/email-otp/send-verification-otp",
    "/email-otp/check-verification-otp",
    "/email-otp/verify-email",
    "/email-otp/request-password-reset",
    "/email-otp/reset-password",
    "/forget-password/email-otp",
    "/email-otp/request-email-change",
    "/email-otp/change-email",
  ],
  plugins: [
    emailOTP({
      otpLength: VERIFICATION_CODE_LENGTH,
      expiresIn: VERIFICATION_CODE_MINUTES * 60,
      allowedAttempts: 5,
      storeOTP: "hashed",
      // Codes only verify e-mails; they never create accounts (consent is asked at sign-up).
      disableSignUp: true,
      overrideDefaultEmailVerification: true,
      sendVerificationOTP: ({ email, otp }) => sendVerificationCode(email, otp),
    }),
    // Lets server actions set the session cookie. Must stay the last plugin.
    nextCookies(),
  ],
});
